/**
 * 探索の隔離 — ツール出力を主コンテキストに入れない層。
 *
 * パターンA（出力を削る）・B（大きく読ませない）はどちらも
 * **主コンテキストにツール出力が入ることを前提に、量を減らす**方式だった。
 * こちらは入れない。
 *
 * 実測（`.bench/turns.jsonl` / 12ターン×3モード）:
 *
 * | モード | $/turn | in の構成比 | cacheCreate | cacheRead |
 * |---|---|---|---|---|
 * | `stateless` | 1.025 | **0.0%** | 45.9% | 28.2% |
 * | `recent` | 0.886 | **0.0%** | 46.5% | 24.7% |
 * | `full` | 0.613 | **0.0%** | 23.2% | 38.2% |
 *
 * `cacheCreate` + `cacheRead` が 6〜7割を占める。これはラリー内部で
 * ツール出力が prefix に積まれ、エージェントループの各ステップで
 * 読み直されているぶんである。10ファイル読んで1つが要る調査だと、
 * 残り9ファイルぶんを以降の全ステップで運び続ける。
 *
 * SDK の `agents` でサブエージェントを定義すると、そのツール出力は
 * **サブエージェント側のコンテキストに留まり**、主スレッドには
 * 最終報告だけが返る。運ぶ量が「読んだ全量」から「結論」に変わる。
 *
 * | 方式 | ツール出力の行き先 | 弱点 |
 * |---|---|---|
 * | A: 出力を削る | 主コンテキスト（中略済み） | 削った所に答えがあると読み直しになる |
 * | B: 入力を絞る | 主コンテキスト（範囲のみ） | 全文が要るときに邪魔 |
 * | C: 隔離（本方式） | サブエージェント内 | 報告の質に依存する。要約で落ちた情報は主スレッドから見えない |
 *
 * この層は SDK にも VSCode にも依存しない。定義と判断だけを持つ。
 */

/** サブエージェント定義。SDK の AgentDefinition に渡す形。 */
export interface ExplorerDefinition {
  description: string;
  prompt: string;
  tools: string[];
  model?: string;
}

/**
 * 探索担当のサブエージェント。
 *
 * 書き込み系ツールを与えない。探索が副作用を持つと、
 * 主スレッドが知らないうちにファイルが変わる
 * （規律エンジンは主スレッドの canUseTool に載っているため、
 * サブエージェント経由の書き込みは同じ検査を通らない）。
 *
 * model を明示しない。既定のサブエージェントモデルに委ねる
 * （安いモデルに固定すると、探索の判断が要る場面で誤った報告が返り、
 * 主スレッドがそれを前提に進んで余計な往復が生まれる）。
 */
export const EXPLORER: ExplorerDefinition = {
  description:
    "コードベースの調査・検索・ファイル内容の確認を行う。" +
    "読んだ内容そのものではなく、判断に要る結論だけを返すこと。",
  tools: ["Read", "Grep", "Glob", "Bash"],
  prompt: [
    "あなたは調査担当である。主スレッドの代わりにファイルを読み、検索し、結論を報告する。",
    "",
    "**あなたが読んだ内容は主スレッドには渡らない。報告した分だけが渡る。**",
    "だから報告は「読んだものの引き写し」ではなく「判断に使える結論」にする。",
    "",
    "## 報告の形",
    "",
    "- **答え** — 問いに対する結論を最初に1〜3文で書く",
    "- **根拠** — どのファイルの何行目がそう言っているか（`path:line` 形式）。",
    "  引用は結論の裏付けに要る最小限だけ。ファイルを丸ごと貼らない",
    "- **わからなかったこと** — 調べたが確認できなかった点。",
    "  ここを省くと、主スレッドは確認済みだと誤解して進む",
    "",
    "## やってはいけないこと",
    "",
    "- ファイルの内容をそのまま長々と貼る（それでは隔離した意味がない）",
    "- 読んでいないことを読んだように書く",
    "- 確認できなかった点を黙って省く",
    "- ファイルを書き換える（あなたに書き込み権限は無い。必要なら報告で主スレッドに渡す）",
  ].join("\n"),
};

/**
 * 探索を隔離すべき指示か判定する。
 *
 * 判定を誤って隔離すると、主スレッドがファイルを直接見られなくなり
 * 編集の精度が落ちる。だから**調査だと明確に読めるときだけ**隔離する。
 *
 * 編集・実装の指示は隔離しない。編集は読んだ内容を主コンテキストに
 * 置いたまま進めるほうが正確で、往復も少ない。
 */
export function shouldDelegate(instruction: string): boolean {
  const text = instruction.trim();
  if (text === "") {
    return false;
  }

  // 編集・実装の意図が読めるなら隔離しない（読んだ内容を手元に置く必要がある）。
  //
  // 「実装」「修正」等は名詞としても使われる（「どこで実装されてるか調べて」は調査）。
  // 単語の存在だけで判定すると調査を編集と誤読するので、
  // **依頼の形（〜して / 〜してほしい）になっているものだけ**を編集とみなす。
  const editing =
    /(直して|直す|修正して|実装して|追加して|書いて|書き換え|変更して|リファクタ|消して|削除して|作って|commit|コミット)/.test(
      text,
    );
  if (editing) {
    return false;
  }

  // 調査の意図が読めるときだけ隔離する
  return /(調べ|探して|どこ|どうなって|確認して|一覧|把握|読んで|洗い出|把握したい|何がある)/.test(
    text,
  );
}

/** SDK の options.agents に載せる形へ変換する。 */
export function toAgentsOption(
  def: ExplorerDefinition = EXPLORER,
): Record<string, Record<string, unknown>> {
  return {
    explorer: {
      description: def.description,
      prompt: def.prompt,
      tools: def.tools,
      ...(def.model !== undefined ? { model: def.model } : {}),
    },
  };
}

